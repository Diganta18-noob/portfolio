-- Run in your own Supabase SQL Editor. Owns policies on the five portfolio tables.
-- Replaces earlier template policies so draft projects and private messages stay protected.
begin;
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null check (role in ('admin','user')),
  created_at timestamptz not null default now()
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  "Title" text not null, "Description" text, "Img" text, "Link" text, "Github" text,
  "Features" jsonb default '[]', "TechStack" jsonb default '[]',
  is_published boolean not null default true,
  order_index integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  "Img" text not null, created_at timestamptz not null default now()
);
create table if not exists public.portfolio_comments (
  id uuid primary key default gen_random_uuid(),
  user_name text not null check (char_length(trim(user_name)) between 1 and 80),
  content text not null check (char_length(trim(content)) between 1 and 2000),
  profile_image text, is_pinned boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 100),
  email text not null check (char_length(email) <= 254),
  message text not null check (char_length(trim(message)) between 1 and 5000),
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
-- Upgrade older template tables in place: CREATE TABLE IF NOT EXISTS does not add columns.
-- Keep existing ids and records; defaults preserve previously public projects.
alter table public.projects
  add column if not exists "Title" text,
  add column if not exists "Description" text,
  add column if not exists "Img" text,
  add column if not exists "Link" text,
  add column if not exists "Github" text,
  add column if not exists "Features" jsonb default '[]'::jsonb,
  add column if not exists "TechStack" jsonb default '[]'::jsonb,
  add column if not exists is_published boolean not null default true,
  add column if not exists order_index integer not null default 0,
  add column if not exists created_at timestamptz not null default now();
alter table public.certificates
  add column if not exists "Img" text,
  add column if not exists created_at timestamptz not null default now();
alter table public.portfolio_comments
  add column if not exists user_name text,
  add column if not exists content text,
  add column if not exists profile_image text,
  add column if not exists is_pinned boolean not null default false,
  add column if not exists created_at timestamptz not null default now();
alter table public.profiles
  add column if not exists username text,
  add column if not exists role text not null default 'user',
  add column if not exists created_at timestamptz not null default now();

create index if not exists contact_messages_email_created on public.contact_messages(email,created_at desc);
create index if not exists contact_messages_created on public.contact_messages(created_at desc);

create or replace function public.is_portfolio_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;
revoke all on function public.is_portfolio_admin() from public;
grant execute on function public.is_portfolio_admin() to anon, authenticated;

-- Remove inherited policies on these app-owned tables, including broad template reads.
do $$ declare item record; begin
  for item in select schemaname,tablename,policyname from pg_policies
    where schemaname='public' and tablename in ('profiles','projects','certificates','portfolio_comments','contact_messages')
  loop execute format('drop policy %I on %I.%I',item.policyname,item.schemaname,item.tablename); end loop;
end $$;
alter table public.profiles enable row level security;
alter table public.projects enable row level security;
alter table public.certificates enable row level security;
alter table public.portfolio_comments enable row level security;
alter table public.contact_messages enable row level security;

revoke all on public.profiles, public.projects, public.certificates, public.portfolio_comments, public.contact_messages from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on public.projects,public.certificates,public.portfolio_comments to anon;
grant select on public.profiles to authenticated;
grant select,insert,update,delete on public.projects,public.certificates,public.portfolio_comments to authenticated;
grant insert(user_name,content,profile_image,is_pinned) on public.portfolio_comments to anon;
grant select,update,delete on public.contact_messages to authenticated;
-- Older installations may use UUID ids or differently named sequences.
do $$ declare table_name text; sequence_name text; begin
  foreach table_name in array array['public.projects','public.certificates'] loop
    sequence_name := pg_get_serial_sequence(table_name,'id');
    if sequence_name is not null then
      execute format('grant usage,select on sequence %s to authenticated',sequence_name);
    end if;
  end loop;
end $$;

create policy profile_self_read on public.profiles for select to authenticated using (id=(select auth.uid()));
-- Profiles are provisioned in the SQL Editor only; browser users cannot grant themselves admin.
create policy projects_public_read on public.projects for select to anon,authenticated using (is_published=true or public.is_portfolio_admin());
create policy projects_admin_write on public.projects for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());
create policy certificates_public_read on public.certificates for select to anon,authenticated using (true);
create policy certificates_admin_write on public.certificates for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());
create policy comments_public_read on public.portfolio_comments for select to anon,authenticated using (true);
create policy comments_public_insert on public.portfolio_comments for insert to anon,authenticated with check (
  is_pinned=false and char_length(trim(user_name)) between 1 and 80 and char_length(trim(content)) between 1 and 2000
);
create policy comments_admin_update on public.portfolio_comments for update to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());
create policy comments_admin_delete on public.portfolio_comments for delete to authenticated using (public.is_portfolio_admin());
create policy messages_admin_read on public.contact_messages for select to authenticated using (public.is_portfolio_admin());
create policy messages_admin_update on public.contact_messages for update to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());
create policy messages_admin_delete on public.contact_messages for delete to authenticated using (public.is_portfolio_admin());

-- Anonymous clients may submit, never list/read, private messages. No direct insert grant.
create or replace function public.submit_contact_message(sender_name text,sender_email text,message_body text) returns void
language plpgsql security definer set search_path = '' as $$
declare normalized_email text := lower(trim(sender_email));
begin
  if sender_name is null or char_length(trim(sender_name)) not between 1 and 100 then raise exception 'Invalid name'; end if;
  if sender_email is null or char_length(normalized_email)>254 or normalized_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then raise exception 'Invalid email'; end if;
  if message_body is null or char_length(trim(message_body)) not between 1 and 5000 then raise exception 'Invalid message'; end if;
  perform pg_advisory_xact_lock(hashtextextended(normalized_email,0));
  if (select count(*) from public.contact_messages where email=normalized_email and created_at>now()-interval '1 hour') >= 5 then
    raise exception 'Too many messages. Please try again later.';
  end if;
  insert into public.contact_messages(name,email,message) values(trim(sender_name),normalized_email,trim(message_body));
end;
$$;
revoke all on function public.submit_contact_message(text,text,text) from public;
grant execute on function public.submit_contact_message(text,text,text) to anon,authenticated;

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('project-images','project-images',true,5242880,array['image/png','image/jpeg','image/webp']),
       ('certificate-images','certificate-images',true,5242880,array['image/png','image/jpeg','image/webp']),
       ('profile-images','profile-images',true,5242880,array['image/png','image/jpeg','image/webp'])
on conflict(id) do update set public=excluded.public,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;
-- Scope policy replacement to policies that mention the portfolio buckets. Keep unrelated buckets intact.
do $$ declare item record; begin
  for item in select policyname from pg_policies where schemaname='storage' and tablename='objects'
    and (coalesce(qual,'') || coalesce(with_check,'')) ~ '(project-images|certificate-images|profile-images)'
  loop execute format('drop policy %I on storage.objects',item.policyname); end loop;
end $$;
create policy portfolio_images_read on storage.objects for select to anon,authenticated using (bucket_id in ('project-images','certificate-images','profile-images'));
create policy portfolio_admin_image_insert on storage.objects for insert to authenticated with check (bucket_id in ('project-images','certificate-images','profile-images') and public.is_portfolio_admin());
create policy portfolio_admin_image_delete on storage.objects for delete to authenticated using (bucket_id in ('project-images','certificate-images','profile-images') and public.is_portfolio_admin());
-- Anonymous image uploads are intentionally disabled. The public guestbook accepts text only.
-- Idempotent realtime opt-in; the UI also refreshes its own comment submissions.
do $$ begin
  if exists(select 1 from pg_publication where pubname='supabase_realtime') and not exists(
    select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='portfolio_comments'
  ) then alter publication supabase_realtime add table public.portfolio_comments; end if;
end $$;
commit;
